#include "preforth.h"

const char *aot_default_shared_ext(void) {
#if defined(_WIN32) || defined(_WIN64)
    return ".dll";
#elif defined(__APPLE__)
    return ".dylib";
#else
    return ".so";
#endif
}

static const char *c_type_str(FFIType t) {
    switch (t) {
        case FFI_VOID: return "void";
        case FFI_I32:  return "int32_t";
        case FFI_U32:  return "uint32_t";
        case FFI_I64:  return "int64_t";
        case FFI_U64:  return "uint64_t";
        case FFI_F64:  return "double";
        case FFI_PTR:  return "void*";
        case FFI_STR:  return "char*";
        default:       return "int64_t";
    }
}

static bool is_standard_c_func(const char *name) {
    static const char *std_funcs[] = {
        "abs", "labs", "llabs", "fabs", "sin", "cos", "tan", "sqrt",
        "malloc", "free", "realloc", "calloc", "printf", "puts", "qsort",
        "strlen", "strcmp", "strcpy", "memcpy", "memset", NULL
    };
    for (int i = 0; std_funcs[i]; i++) {
        if (strcmp(std_funcs[i], name) == 0) return true;
    }
    return false;
}

static const char *find_var_name_for_slot(VM *vm, void *slot) {
    for (size_t i = 0; i < vm->word_count; i++) {
        if (vm->words[i]->kind == WORD_VAR && vm->words[i]->var_slot == slot) {
            return vm->words[i]->name;
        }
    }
    return NULL;
}

bool aot_emit_c_source(VM *vm, FILE *out) {
    if (!vm || !out) return false;

    // 1. Headers
    fprintf(out, "/* Generated by PreForth AOT Compiler */\n");
    fprintf(out, "#include <stdint.h>\n");
    fprintf(out, "#include <stdbool.h>\n");
    fprintf(out, "#include <stdlib.h>\n");
    fprintf(out, "#include <stdio.h>\n");
    fprintf(out, "#include <string.h>\n");
    fprintf(out, "#include <math.h>\n\n");

    // 2. Export macro
    fprintf(out, "#if defined(_WIN32) || defined(_WIN64)\n");
    fprintf(out, "#define PF_EXPORT __declspec(dllexport)\n");
    fprintf(out, "#else\n");
    fprintf(out, "#define PF_EXPORT __attribute__((visibility(\"default\")))\n");
    fprintf(out, "#endif\n\n");

    // 3. Thread-local Data Stack
    fprintf(out, "#define PF_STACK_CAP 8192\n");
    fprintf(out, "static int64_t pf_stack[PF_STACK_CAP];\n");
    fprintf(out, "static int pf_sp = 0;\n\n");

    fprintf(out, "static inline void pf_push(int64_t v) {\n");
    fprintf(out, "    if (pf_sp < PF_STACK_CAP) pf_stack[pf_sp++] = v;\n");
    fprintf(out, "}\n\n");

    fprintf(out, "static inline int64_t pf_pop(void) {\n");
    fprintf(out, "    return (pf_sp > 0) ? pf_stack[--pf_sp] : 0;\n");
    fprintf(out, "}\n\n");

    fprintf(out, "static inline int64_t pf_peek(void) {\n");
    fprintf(out, "    return (pf_sp > 0) ? pf_stack[pf_sp - 1] : 0;\n");
    fprintf(out, "}\n\n");

    // 4. Variables
    for (size_t i = 0; i < vm->word_count; i++) {
        if (vm->words[i]->kind == WORD_VAR) {
            fprintf(out, "static int64_t pf_var_%s = 0;\n", vm->words[i]->name);
        }
    }
    fprintf(out, "\n");

    // 5. Imports (extern C declarations)
    for (size_t i = 0; i < vm->import_count; i++) {
        ImportEntry *imp = &vm->imports[i];
        if (!is_standard_c_func(imp->name)) {
            fprintf(out, "extern %s %s(", c_type_str(imp->ret_type), imp->name);
            for (int a = 0; a < imp->arg_count; a++) {
                fprintf(out, "%s%s", c_type_str(imp->arg_types[a]), (a + 1 < imp->arg_count) ? ", " : "");
            }
            if (imp->arg_count == 0) fprintf(out, "void");
            fprintf(out, ");\n");
        }
    }
    fprintf(out, "\n");

    // 6. Word forward declarations
    for (size_t i = 0; i < vm->word_count; i++) {
        if (vm->words[i]->kind == WORD_BYTECODE) {
            fprintf(out, "static void pf_word_%s(void);\n", vm->words[i]->name);
        }
    }
    fprintf(out, "\n");

    // 7. Word definitions
    for (size_t i = 0; i < vm->word_count; i++) {
        Word *w = vm->words[i];
        if (w->kind != WORD_BYTECODE || !w->bytecode) continue;

        BytecodeBlock *bb = w->bytecode;
        fprintf(out, "static void pf_word_%s(void) {\n", w->name);

        for (size_t ip = 0; ip < bb->count; ip++) {
            Instruction inst = bb->code[ip];
            fprintf(out, "L_%zu: ", ip);

            switch (inst.op) {
                case OP_NOP:
                    fprintf(out, ";\n");
                    break;
                case OP_LIT_INT:
                    fprintf(out, "pf_push((int64_t)%lldLL);\n", (long long)inst.val.as.i);
                    break;
                case OP_LIT_FLOAT: {
                    double f = inst.val.as.f;
                    uint64_t raw;
                    memcpy(&raw, &f, sizeof(double));
                    fprintf(out, "{ double f = %g; int64_t raw; memcpy(&raw, &f, sizeof(double)); pf_push(raw); }\n", f);
                    break;
                }
                case OP_LIT_STR:
                    fprintf(out, "pf_push((int64_t)(uintptr_t)\"%s\");\n", inst.val.as.str ? inst.val.as.str : "");
                    break;
                case OP_LIT_PTR: {
                    const char *vname = find_var_name_for_slot(vm, inst.val.as.ptr);
                    if (vname) {
                        fprintf(out, "pf_push((int64_t)(uintptr_t)&pf_var_%s);\n", vname);
                    } else {
                        fprintf(out, "pf_push((int64_t)(uintptr_t)%p);\n", inst.val.as.ptr);
                    }
                    break;
                }
                case OP_CALL: {
                    int w_idx = (int)inst.arg;
                    if (w_idx >= 0 && (size_t)w_idx < vm->word_count) {
                        Word *callee = vm->words[w_idx];
                        if (callee->kind == WORD_VAR) {
                            fprintf(out, "pf_push((int64_t)(uintptr_t)&pf_var_%s);\n", callee->name);
                        } else if (callee->kind == WORD_BYTECODE) {
                            fprintf(out, "pf_word_%s();\n", callee->name);
                        } else if (callee->kind == WORD_EXTERN && callee->extern_fn) {
                            // Call extern function
                            ExternFunc *ef = callee->extern_fn;
                            fprintf(out, "{\n");
                            for (int a = 0; a < ef->arg_count; a++) {
                                fprintf(out, "    int64_t a%d = pf_pop();\n", a);
                            }
                            if (ef->ret_type != FFI_VOID) {
                                fprintf(out, "    int64_t res = (int64_t)%s(", ef->name);
                            } else {
                                fprintf(out, "    %s(", ef->name);
                            }
                            for (int a = 0; a < ef->arg_count; a++) {
                                fprintf(out, "(%s)a%d%s", c_type_str(ef->arg_types[a]), a, (a + 1 < ef->arg_count) ? ", " : "");
                            }
                            fprintf(out, ");\n");
                            if (ef->ret_type != FFI_VOID) {
                                fprintf(out, "    pf_push(res);\n");
                            }
                            fprintf(out, "}\n");
                        }
                    }
                    break;
                }
                case OP_FFI_CALL: {
                    int w_idx = (int)inst.arg;
                    if (w_idx >= 0 && (size_t)w_idx < vm->word_count) {
                        Word *callee = vm->words[w_idx];
                        if (callee->kind == WORD_EXTERN && callee->extern_fn) {
                            ExternFunc *ef = callee->extern_fn;
                            fprintf(out, "{\n");
                            for (int a = 0; a < ef->arg_count; a++) {
                                fprintf(out, "    int64_t a%d = pf_pop();\n", a);
                            }
                            if (ef->ret_type != FFI_VOID) {
                                fprintf(out, "    int64_t res = (int64_t)%s(", ef->name);
                            } else {
                                fprintf(out, "    %s(", ef->name);
                            }
                            for (int a = 0; a < ef->arg_count; a++) {
                                fprintf(out, "(%s)a%d%s", c_type_str(ef->arg_types[a]), a, (a + 1 < ef->arg_count) ? ", " : "");
                            }
                            fprintf(out, ");\n");
                            if (ef->ret_type != FFI_VOID) {
                                fprintf(out, "    pf_push(res);\n");
                            }
                            fprintf(out, "}\n");
                        }
                    }
                    break;
                }
                case OP_RET:
                    fprintf(out, "return;\n");
                    break;
                case OP_JMP:
                    fprintf(out, "goto L_%lld;\n", (long long)inst.arg);
                    break;
                case OP_JZ:
                    fprintf(out, "{ int64_t cond = pf_pop(); if (!cond) goto L_%lld; }\n", (long long)inst.arg);
                    break;
                case OP_JNZ:
                    fprintf(out, "{ int64_t cond = pf_pop(); if (cond) goto L_%lld; }\n", (long long)inst.arg);
                    break;
                case OP_DUP:
                    fprintf(out, "pf_push(pf_peek());\n");
                    break;
                case OP_DROP:
                    fprintf(out, "pf_pop();\n");
                    break;
                case OP_SWAP:
                    fprintf(out, "{ int64_t a = pf_pop(); int64_t b = pf_pop(); pf_push(a); pf_push(b); }\n");
                    break;
                case OP_OVER:
                    fprintf(out, "pf_push(pf_stack[pf_sp - 2]);\n");
                    break;
                case OP_ADD:
                    fprintf(out, "{ int64_t lhs = pf_pop(); int64_t rhs = pf_pop(); pf_push(lhs + rhs); }\n");
                    break;
                case OP_SUB:
                    fprintf(out, "{ int64_t lhs = pf_pop(); int64_t rhs = pf_pop(); pf_push(lhs - rhs); }\n");
                    break;
                case OP_MUL:
                    fprintf(out, "{ int64_t lhs = pf_pop(); int64_t rhs = pf_pop(); pf_push(lhs * rhs); }\n");
                    break;
                case OP_DIV:
                    fprintf(out, "{ int64_t lhs = pf_pop(); int64_t rhs = pf_pop(); pf_push(rhs != 0 ? lhs / rhs : 0); }\n");
                    break;
                case OP_MOD:
                    fprintf(out, "{ int64_t lhs = pf_pop(); int64_t rhs = pf_pop(); pf_push(rhs != 0 ? lhs %% rhs : 0); }\n");
                    break;
                case OP_INC:
                    fprintf(out, "{ int64_t v = pf_pop(); pf_push(v + 1); }\n");
                    break;
                case OP_DEC:
                    fprintf(out, "{ int64_t v = pf_pop(); pf_push(v - 1); }\n");
                    break;
                case OP_NEG:
                    fprintf(out, "{ int64_t v = pf_pop(); pf_push(-v); }\n");
                    break;
                case OP_EQ:
                    fprintf(out, "{ int64_t lhs = pf_pop(); int64_t rhs = pf_pop(); pf_push(lhs == rhs ? 1 : 0); }\n");
                    break;
                case OP_NEQ:
                    fprintf(out, "{ int64_t lhs = pf_pop(); int64_t rhs = pf_pop(); pf_push(lhs != rhs ? 1 : 0); }\n");
                    break;
                case OP_LT:
                    fprintf(out, "{ int64_t lhs = pf_pop(); int64_t rhs = pf_pop(); pf_push(lhs < rhs ? 1 : 0); }\n");
                    break;
                case OP_GT:
                    fprintf(out, "{ int64_t lhs = pf_pop(); int64_t rhs = pf_pop(); pf_push(lhs > rhs ? 1 : 0); }\n");
                    break;
                case OP_LE:
                    fprintf(out, "{ int64_t lhs = pf_pop(); int64_t rhs = pf_pop(); pf_push(lhs <= rhs ? 1 : 0); }\n");
                    break;
                case OP_GE:
                    fprintf(out, "{ int64_t lhs = pf_pop(); int64_t rhs = pf_pop(); pf_push(lhs >= rhs ? 1 : 0); }\n");
                    break;
                case OP_AND:
                    fprintf(out, "{ int64_t lhs = pf_pop(); int64_t rhs = pf_pop(); pf_push(lhs & rhs); }\n");
                    break;
                case OP_OR:
                    fprintf(out, "{ int64_t lhs = pf_pop(); int64_t rhs = pf_pop(); pf_push(lhs | rhs); }\n");
                    break;
                case OP_XOR:
                    fprintf(out, "{ int64_t lhs = pf_pop(); int64_t rhs = pf_pop(); pf_push(lhs ^ rhs); }\n");
                    break;
                case OP_NOT:
                    fprintf(out, "{ int64_t v = pf_pop(); pf_push(v == 0 ? 1 : 0); }\n");
                    break;
                case OP_SHL:
                    fprintf(out, "{ int64_t lhs = pf_pop(); int64_t rhs = pf_pop(); pf_push(lhs << rhs); }\n");
                    break;
                case OP_SHR:
                    fprintf(out, "{ int64_t lhs = pf_pop(); int64_t rhs = pf_pop(); pf_push((uint64_t)lhs >> rhs); }\n");
                    break;
                case OP_FETCH:
                    fprintf(out, "{ void *addr = (void *)(uintptr_t)pf_pop(); pf_push(addr ? *(int64_t*)addr : 0); }\n");
                    break;
                case OP_STORE:
                    fprintf(out, "{ void *addr = (void *)(uintptr_t)pf_pop(); int64_t val = pf_pop(); if (addr) *(int64_t*)addr = val; }\n");
                    break;
                case OP_C_FETCH8:
                    fprintf(out, "{ void *addr = (void *)(uintptr_t)pf_pop(); pf_push(addr ? *(uint8_t*)addr : 0); }\n");
                    break;
                case OP_C_FETCH32:
                    fprintf(out, "{ void *addr = (void *)(uintptr_t)pf_pop(); pf_push(addr ? *(int32_t*)addr : 0); }\n");
                    break;
                case OP_C_FETCH64:
                    fprintf(out, "{ void *addr = (void *)(uintptr_t)pf_pop(); pf_push(addr ? *(int64_t*)addr : 0); }\n");
                    break;
                case OP_C_STORE8:
                    fprintf(out, "{ void *addr = (void *)(uintptr_t)pf_pop(); int64_t val = pf_pop(); if (addr) *(uint8_t*)addr = (uint8_t)val; }\n");
                    break;
                case OP_C_STORE32:
                    fprintf(out, "{ void *addr = (void *)(uintptr_t)pf_pop(); int64_t val = pf_pop(); if (addr) *(int32_t*)addr = (int32_t)val; }\n");
                    break;
                case OP_C_STORE64:
                    fprintf(out, "{ void *addr = (void *)(uintptr_t)pf_pop(); int64_t val = pf_pop(); if (addr) *(int64_t*)addr = val; }\n");
                    break;
                case OP_CSTR:
                    fprintf(out, "{ void *addr = (void *)(uintptr_t)pf_pop(); pf_push((int64_t)(uintptr_t)addr); }\n");
                    break;
                case OP_PRINT:
                    fprintf(out, "{ int64_t v = pf_pop(); printf(\"%%lld\\n\", (long long)v); fflush(stdout); }\n");
                    break;
                default:
                    fprintf(out, ";\n");
                    break;
            }
        }
        fprintf(out, "L_end: return;\n");
        fprintf(out, "}\n\n");
    }

    // 8. Exported C ABI Functions (Phase 7.2)
    for (size_t i = 0; i < vm->export_count; i++) {
        ExportEntry *exp = &vm->exports[i];

        fprintf(out, "PF_EXPORT %s %s(", c_type_str(exp->ret_type), exp->c_symbol_name);
        for (int a = 0; a < exp->arg_count; a++) {
            fprintf(out, "%s a%d%s", c_type_str(exp->arg_types[a]), a, (a + 1 < exp->arg_count) ? ", " : "");
        }
        if (exp->arg_count == 0) fprintf(out, "void");
        fprintf(out, ") {\n");

        // Prologue: Push incoming C arguments in reverse order (argN-1 down to arg0)
        // so arg0 sits at Top-of-Stack when word begins
        for (int a = exp->arg_count - 1; a >= 0; a--) {
            fprintf(out, "    pf_push((int64_t)a%d);\n", a);
        }

        // Body: Execute the PreForth word
        fprintf(out, "    pf_word_%s();\n", exp->word_name);

        // Epilogue: Pop top of PreForth stack and return in native C return register
        if (exp->ret_type != FFI_VOID) {
            fprintf(out, "    return (%s)pf_pop();\n", c_type_str(exp->ret_type));
        }
        fprintf(out, "}\n\n");
    }

    return true;
}

bool aot_emit_c_file(VM *vm, const char *out_c_filename) {
    FILE *f = fopen(out_c_filename, "w");
    if (!f) {
        vm_error(vm, "Could not open '%s' for writing C source", out_c_filename);
        return false;
    }
    bool ok = aot_emit_c_source(vm, f);
    fclose(f);
    return ok;
}

bool aot_build_shared(VM *vm, const char *out_filename) {
    char temp_c[512];
    snprintf(temp_c, sizeof(temp_c), "_pf_aot_%u.c", (unsigned int)rand());

    if (!aot_emit_c_file(vm, temp_c)) {
        return false;
    }

    // Build command: zig cc -shared -fPIC -O2 <temp_c> -o <out_filename> -l<lib...>
    char cmd[2048];
    snprintf(cmd, sizeof(cmd), "zig cc -shared -fPIC -O2 -Wno-absolute-value -Wno-deprecated-declarations \"%s\" -o \"%s\"", temp_c, out_filename);

    for (size_t i = 0; i < vm->link_lib_count; i++) {
        strncat(cmd, " -l", sizeof(cmd) - strlen(cmd) - 1);
        strncat(cmd, vm->link_libs[i], sizeof(cmd) - strlen(cmd) - 1);
    }

    int ret = system(cmd);
    remove(temp_c);

    if (ret != 0) {
        vm_error(vm, "Failed to compile shared library '%s' (zig cc returned %d)", out_filename, ret);
        return false;
    }

    return true;
}

bool aot_build_object(VM *vm, const char *out_filename) {
    char temp_c[512];
    snprintf(temp_c, sizeof(temp_c), "_pf_aot_obj_%u.c", (unsigned int)rand());

    if (!aot_emit_c_file(vm, temp_c)) {
        return false;
    }

    char cmd[2048];
    snprintf(cmd, sizeof(cmd), "zig cc -c -fPIC -O2 -Wno-absolute-value -Wno-deprecated-declarations \"%s\" -o \"%s\"", temp_c, out_filename);

    int ret = system(cmd);
    remove(temp_c);

    if (ret != 0) {
        vm_error(vm, "Failed to compile object file '%s' (zig cc returned %d)", out_filename, ret);
        return false;
    }

    return true;
}
